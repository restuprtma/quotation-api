package service

import (
	"bytes"
	"context"
	"encoding/json"
	"fmt"
	"io"
	"net/http"

	"venturo-skeleton-go/internal/config"
	"venturo-skeleton-go/internal/modules/quotation/dto"
	"venturo-skeleton-go/pkg/logger"

	"go.uber.org/zap"
)

type GeminiProvider struct {
	cfg config.AIConfig
}

func NewGeminiProvider(cfg config.AIConfig) *GeminiProvider {
	return &GeminiProvider{cfg: cfg}
}

func (p *GeminiProvider) GenerateDraft(ctx context.Context, req *dto.AIGenerateRequest) (*dto.AIGenerateResponse, error) {
	sysPrompt := buildSystemPrompt()
	userPrompt := buildUserPrompt(req)

	// Gemini REST payload structure
	payload := map[string]interface{}{
		"systemInstruction": map[string]interface{}{
			"parts": []map[string]string{{"text": sysPrompt}},
		},
		"contents": []map[string]interface{}{
			{
				"parts": []map[string]string{{"text": userPrompt}},
			},
		},
		"generationConfig": map[string]interface{}{
			"responseMimeType": "application/json",
		},
	}
	body, _ := json.Marshal(payload)

	var lastErr error
	for i := 0; i < 3; i++ {
		res, err := p.doRequest(ctx, body)
		if err != nil {
			logger.Warn("Gemini request failed", zap.Error(err), zap.Int("attempt", i+1))
			lastErr = err
			continue
		}

		var draft dto.AIGenerateResponse
		if err := json.Unmarshal([]byte(res), &draft); err != nil {
			logger.Warn("Failed to unmarshal Gemini JSON", zap.Error(err))
			lastErr = fmt.Errorf("invalid json format from provider: %w", err)
			continue
		}

		if err := ValidateAIBundle(&draft); err != nil {
			logger.Warn("Gemini bundle validation failed", zap.Error(err))
			return nil, err // Do not retry validation errors
		}

		return &draft, nil
	}

	return nil, fmt.Errorf("gemini provider failed after retries: %w", lastErr)
}

func (p *GeminiProvider) doRequest(ctx context.Context, body []byte) (string, error) {
	url := fmt.Sprintf("https://generativelanguage.googleapis.com/v1beta/models/%s:generateContent?key=%s", p.cfg.GeminiModel, p.cfg.GeminiAPIKey)

	req, err := http.NewRequestWithContext(ctx, "POST", url, bytes.NewReader(body))
	if err != nil {
		return "", err
	}
	req.Header.Set("Content-Type", "application/json")

	client := &http.Client{Timeout: p.cfg.Timeout}
	resp, err := client.Do(req)
	if err != nil {
		return "", err
	}
	defer resp.Body.Close()

	if resp.StatusCode >= 500 {
		return "", fmt.Errorf("gemini server error: %d", resp.StatusCode)
	}
	if resp.StatusCode == 429 {
		return "", fmt.Errorf("gemini rate limit exceeded") // Worth retrying if we added backoff, but let's just retry
	}
	if resp.StatusCode != 200 {
		return "", fmt.Errorf("gemini returned status %d", resp.StatusCode)
	}

	respBody, err := io.ReadAll(resp.Body)
	if err != nil {
		return "", err
	}

	var result struct {
		Candidates []struct {
			Content struct {
				Parts []struct {
					Text string `json:"text"`
				} `json:"parts"`
			} `json:"content"`
		} `json:"candidates"`
	}

	if err := json.Unmarshal(respBody, &result); err != nil {
		return "", err
	}

	if len(result.Candidates) == 0 || len(result.Candidates[0].Content.Parts) == 0 {
		return "", fmt.Errorf("no response generated by gemini")
	}

	return result.Candidates[0].Content.Parts[0].Text, nil
}
